def build_label_mapping(reference_dir: str = None, experiment_name: str = None):
    """
    策略 B 副本（2026-08-14）：固定网格直构 label→Hz 映射表。

    原版从 MERT 参考 JSON（f0_label+f0 两列）建表——B 实验无对应参考文件，
    且参考只覆盖 Josh 数据范围（≤480 Hz）。700-bin 网格本身是固定的
    （80–1000 Hz、1/192 oct，与刺激 HDF5 的 f0_label_192 同一网格），
    故直接用公式构造，不读任何 reference：
        label_to_hz[i] = 80 × 2^(i/192),  i ∈ [0, 699]

    Returns:
        label_to_hz: np.ndarray of shape (700,) — label → Hz
        label_pairs: dict label → Hz（全 700 个 label）
    """
    i = np.arange(N_CLASSES, dtype=np.float64)
    label_to_hz = 80.0 * np.power(2.0, i / 192.0)
    label_pairs = {int(l): float(hz) for l, hz in enumerate(label_to_hz)}
    return label_to_hz, label_pairs


def hz_to_label(f0_hz: float, label_to_hz: np.ndarray) -> int:
    """
    Convert a continuous Hz value to the nearest class label (0–699).

    Args:
        f0_hz: Frequency in Hz.
        label_to_hz: Array of shape (700,) mapping label → Hz.

    Returns:
        Integer class label.
    """
    if f0_hz <= 0 or np.isnan(f0_hz) or np.isinf(f0_hz):
        return 0

    # Clamp to valid Hz range
    f0_hz = np.clip(f0_hz, label_to_hz[0], label_to_hz[-1])

    # Find closest label by log-distance (cents)
    log_f0 = np.log(f0_hz)
    log_labels = np.log(label_to_hz)
    label = int(np.argmin(np.abs(log_labels - log_f0)))
    return label


def make_probability_vector(pred_label: int, sigma: float = 1.5) -> list:
    """
    Create a 700-element probability distribution centred on pred_label.

    Uses a discretised Gaussian with standard deviation `sigma` (in label
    units, which correspond to approximately 1.5 cents per label step).
    The distribution is normalised to sum to 1.

    Args:
        pred_label: Predicted class label (0–699).
        sigma: Gaussian sigma in label units.

    Returns:
        list of 700 floats summing to 1.
    """
    x = np.arange(N_CLASSES, dtype=np.float64)
    probs = norm.pdf(x, loc=float(pred_label), scale=sigma)
    probs /= probs.sum()  # normalise
    return probs.tolist()


