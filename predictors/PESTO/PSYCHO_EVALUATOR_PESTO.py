def get_audio_from_hdf5(hdf5_path: str, audio_key: str) -> np.ndarray:
    """Extract audio waveform dataset from an HDF5 file."""
    try:
        with h5py.File(hdf5_path, 'r') as f:
            parts = audio_key.split('/')
            obj = f
            for part in parts:
                obj = obj[part]
            return obj[:]
    except Exception as e:
        print(f'  [ERROR] Failed to read "{audio_key}" from {hdf5_path}: {e}')
        return None


def load_reference_template(reference_dir: str, experiment_name: str) -> dict:
    """Load the MERT reference prediction JSON as a structural template."""
    ref_path = os.path.join(reference_dir, f'predictions_mert_{experiment_name}.json')
    if os.path.exists(ref_path):
        with open(ref_path, 'r') as f:
            return json.load(f)
    print(f'  [WARN] Reference template not found: {ref_path}')
    return {}


def get_pesto_vqt_freqs(step_size: float = 10.0, sr: int = 32000):
    """Extract the VQT/CQT bin frequencies (Hz) from the PESTO model.

    v3: pesto does not expose the VQT frequencies through predict(); they
    live on the model's HCQT kernels
    (model.preprocessor.hcqt_kernels.cqt_kernels[0].frequencies).

    Returns:
        np.ndarray (n_bins,) float32, or None if the internal attribute is
        unavailable (in which case the .npz is saved without vqt_freqs).
    """
    try:
        from pesto.loader import load_model
        model = load_model(PESTO_MODEL_NAME, step_size=step_size, sampling_rate=sr)
        freqs = model.preprocessor.hcqt_kernels.cqt_kernels[0].frequencies
        return np.asarray(freqs, dtype=np.float32)
    except Exception as e:
        print(f'  [WARN] Could not extract PESTO VQT frequencies: {e}')
        return None


