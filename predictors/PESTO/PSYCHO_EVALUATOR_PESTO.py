def main():
    parser = argparse.ArgumentParser(
        description='PESTO Psychophysics Evaluator — MERT-compatible output format'
    )
    parser.add_argument('--data_root', type=str, default=DEFAULT_DATA_ROOT)
    parser.add_argument('--output_dir', type=str, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument('--reference_dir', type=str, default=DEFAULT_REFERENCE_DIR)
    parser.add_argument('--step_size', type=float, default=10.0)
    parser.add_argument('--batch_size', type=int, default=256)
    parser.add_argument('--gpu', type=int, default=0)

    parser.add_argument(
        '--experiments', type=str, default=None,
        help='逗号分隔的实验名过滤（如 ERB_B6）；默认 None = 全部 6 个数据集'
    )
    args = parser.parse_args()

    # 策略 B 副本新增: 按数据集过滤（支持 B6 单独试运行/按数据集恢复）
    experiment_filter = None
    if args.experiments:
        experiment_filter = set(
            s.strip() for s in args.experiments.split(',') if s.strip())


    # ------------------------------------------------------------------
    # Setup
    # ------------------------------------------------------------------
    print('=' * 60)
    print('PESTO Psychophysics Evaluator (MERT-compatible format)')
    print('=' * 60)

    data_root = os.path.abspath(args.data_root)
    output_dir = os.path.abspath(args.output_dir)
    reference_dir = os.path.abspath(args.reference_dir)

    print(f'Data root:      {data_root}')
    print(f'Output dir:     {output_dir}')
    print(f'Reference dir:  {reference_dir}')
    print(f'Step size:      {args.step_size} ms')
    print(f'Batch size:     {args.batch_size}')
    print(f'Output classes: {N_CLASSES}')

    os.makedirs(output_dir, exist_ok=True)

    # v3: extract PESTO VQT bin frequencies once (shared by all experiments)
    vqt_freqs = get_pesto_vqt_freqs(step_size=args.step_size)
    if vqt_freqs is not None:
        print(f'  VQT bins: {vqt_freqs.shape[0]} '
              f'({vqt_freqs[0]:.2f}–{vqt_freqs[-1]:.2f} Hz)')

    if args.gpu >= 0 and torch.cuda.is_available():
        device = torch.device(f'cuda:{args.gpu}')
        device_str = 'cuda'
        print(f'Device:         CUDA (GPU {args.gpu})')
    else:
        device = torch.device('cpu')
        device_str = 'cpu'
        print(f'Device:         CPU')

    # ------------------------------------------------------------------
    # Process experiments
    # ------------------------------------------------------------------
    print(f'\n[1/2] Processing experiments with PESTO (step_size={args.step_size}ms)...')

    generated_files = []
    experiments_processed = []
    total_stimuli = 0

    for hdf5_filename, audio_key, experiment_name in EXPERIMENTS:
        if experiment_filter is not None and experiment_name not in experiment_filter:
            print(f"  [SKIP] {experiment_name} (not in --experiments filter)")
            continue
        hdf5_path = os.path.join(data_root, hdf5_filename)

        try:
            result, all_f0_hz, all_confidence, all_activations = process_experiment(
                hdf5_path=hdf5_path,
                audio_key=audio_key,
                experiment_name=experiment_name,
                reference_dir=reference_dir,
                step_size=args.step_size,
                batch_size=args.batch_size,
                device=device,
            )

            if result is None:
                print(f'  ❌ Failed to process {experiment_name}')
                continue

            n_stim = len(result.get('f0_label:labels_pred', []))
            total_stimuli += n_stim

            output_filename = f'predictions_pesto_{experiment_name}.json'
            output_path = os.path.join(output_dir, output_filename)

            with open(output_path, 'w') as f:
                json.dump(result, f, cls=NumpyEncoder, indent=2)

            # v3: Save all raw model outputs alongside JSON (float32, NaN on error)
            f0_arr = np.array([f if f is not None else np.nan for f in all_f0_hz],
                              dtype=np.float32)
            conf_arr = np.array([c if c is not None else np.nan for c in all_confidence],
                                dtype=np.float32)
            act_arr = np.stack([
                a if a is not None else np.full(PESTO_OUTPUT_BINS, np.nan, dtype=np.float32)
                for a in all_activations
            ]).astype(np.float32)  # (n_stimuli, 384)
            npz_path = output_path.replace('.json', '_raw.npz')
            save_kwargs = dict(
                f0_hz=f0_arr,
                confidence=conf_arr,
                activations=act_arr,
                model_name='PESTO',
                experiment_name=experiment_name,
                sigma_used=1.5,
            )
            if vqt_freqs is not None:  # v3: VQT bin frequencies when available
                save_kwargs['vqt_freqs'] = vqt_freqs
            np.savez_compressed(npz_path, **save_kwargs)

            generated_files.append(output_filename)
            experiments_processed.append(experiment_name)

            size_mb = os.path.getsize(output_path) / (1024 * 1024)
            print(f'  ✅ Saved: {output_filename}  ({size_mb:.2f} MB, {n_stim} stimuli)')

        except Exception as e:
            print(f'  ❌ Fatal error processing {experiment_name}: {e}')
            traceback.print_exc()

    # ------------------------------------------------------------------
    # Report
    # ------------------------------------------------------------------
    print(f'\n[2/2] Generating evaluation report...')

    report = generate_evaluation_report(
        generated_files=generated_files,
        experiments_processed=experiments_processed,
        total_stimuli=total_stimuli,
        data_root=data_root,
        output_dir=output_dir,
        step_size=args.step_size,
        device_str=device_str,
        batch_size=args.batch_size,
    )

    report_path = os.path.join(output_dir, 'evaluation_report.json')
    with open(report_path, 'w') as f:
        json.dump(report, f, cls=NumpyEncoder, indent=2)
    print(f'  ✅ Report saved: {report_path}')

    # ------------------------------------------------------------------
    # Summary
    # ------------------------------------------------------------------
    print(f'\n{"=" * 60}')
    print('✅ PESTO Evaluation Complete!')
    print(f'   Experiments:  {len(experiments_processed)}/{len(EXPERIMENTS)}')
    print(f'   Total stimuli: {total_stimuli}')
    print(f'   Output dir:   {output_dir}')
    for fname in generated_files:
        fpath = os.path.join(output_dir, fname)
        size_mb = os.path.getsize(fpath) / (1024 * 1024)
        print(f'     - {fname}  ({size_mb:.2f} MB)')


if __name__ == '__main__':
    main()
