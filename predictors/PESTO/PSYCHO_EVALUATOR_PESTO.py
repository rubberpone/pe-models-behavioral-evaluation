def process_experiment(
    hdf5_path: str,
    audio_key: str,
    experiment_name: str,
    reference_dir: str,
    step_size: float,
    batch_size: int,
    device: torch.device,
) -> dict:
    """
    Process one psychophysics experiment:

    1. Load HDF5 audio
    2. Build per-experiment label→Hz mapping from reference template
    3. Run PESTO on each stimulus (batched GPU inference)
    4. Aggregate frame predictions via median → Hz
    5. Convert Hz → class label (0–699)
    6. Generate 700-element probability vector per stimulus
    7. Save in exact MERT-compatible JSON format
    """
    if not os.path.exists(hdf5_path):
        print(f'  [ERROR] HDF5 file not found: {hdf5_path}')
        return None, None, None, None

    print(f'\n{"=" * 60}')
    print(f'Processing: {experiment_name}')
    print(f'  HDF5:     {hdf5_path}')
    print(f'  Audio key: {audio_key}')

    # ------------------------------------------------------------------
    # 1. Load audio
    # ------------------------------------------------------------------
    audio = get_audio_from_hdf5(hdf5_path, audio_key)
    if audio is None:
        return None, None, None, None

    n_stimuli = audio.shape[0]
    assert audio.shape[1] == 4800, f'Expected 4800 samples, got {audio.shape[1]}'
    print(f'  Stimuli:  {n_stimuli}  |  Audio shape: {audio.shape}')

    # ------------------------------------------------------------------
    # 2. Build label mapping from reference
    # ------------------------------------------------------------------
    label_to_hz, label_pairs = build_label_mapping(reference_dir, experiment_name)
    sorted_labels = sorted(label_pairs.keys())
    print(f'  Label mapping: {len(label_pairs)} unique labels, '
          f'range [{sorted_labels[0]}, {sorted_labels[-1]}], '
          f'Hz range [{label_pairs[sorted_labels[0]]:.1f}, {label_pairs[sorted_labels[-1]]:.1f}]')

    # ------------------------------------------------------------------
    # 3. Load reference template
    # ------------------------------------------------------------------
    template = load_reference_template(reference_dir, experiment_name)

    # ------------------------------------------------------------------
    # 4. Run PESTO in batches
    # ------------------------------------------------------------------
    all_pred_labels = []  # int class labels
    all_pred_probs = []    # 700-element probability vectors
    all_f0_hz = []         # raw regression f0_hz values (pre-label-conversion)
    all_confidence = []    # v4: per-trial mean frame confidence
    all_activations = []   # v4: per-trial frame-mean internal activations (VQT space)
    errors = []

    pbar = tqdm(total=n_stimuli, desc=f'  PESTO → {experiment_name}', unit='stim')

    for batch_start in range(0, n_stimuli, batch_size):
        batch_end = min(batch_start + batch_size, n_stimuli)
        batch_waveforms = audio[batch_start:batch_end]

        try:
            x = torch.as_tensor(batch_waveforms, dtype=torch.float32).to(device)

            with torch.inference_mode():
                _, pitch, confidence, activations = pesto.predict(
                    x, sr=32000, step_size=step_size,
                    reduction='alwa', model_name=PESTO_MODEL_NAME,
                )

            pitch_np = pitch.cpu().numpy()       # (B, n_frames)
            conf_np = confidence.cpu().numpy()    # (B, n_frames)
            act_np = activations.cpu().numpy() if hasattr(activations, 'cpu') else np.asarray(activations)
            # act_np shape: (B, n_frames, n_bins=384) for mir-1k_g7

            for i in range(batch_end - batch_start):
                p_i = pitch_np[i]
                c_i = conf_np[i]
                a_i = act_np[i]  # (n_frames, n_bins)

                # Confidence-based voicing filter
                voiced_mask = c_i > 0.1
                if voiced_mask.any():
                    p_i = p_i[voiced_mask]
                    conf_mean = float(c_i[voiced_mask].mean())  # v3: voiced-frame mean
                else:
                    conf_mean = 0.0

                # Exclude unvoiced frames
                valid = p_i[p_i > 0]

                if len(valid) > 0:
                    f0_hz = float(np.median(valid))
                else:
                    f0_hz = 0.0

                # v3: per-trial activations: mean across frames (float32 to save space)
                act_mean = a_i.mean(axis=0).astype(np.float32)  # (n_bins=384,)

                # Collect raw model outputs before label conversion
                all_f0_hz.append(f0_hz)
                all_confidence.append(conf_mean)
                all_activations.append(act_mean)

                # Convert Hz → class label
                pred_label = hz_to_label(f0_hz, label_to_hz)
                all_pred_labels.append(pred_label)

                # Generate 700-element probability vector
                if f0_hz > 0:
                    prob_vec = make_probability_vector(pred_label, sigma=1.5)
                else:
                    prob_vec = make_probability_vector(0, sigma=100.0)  # flat-ish
                all_pred_probs.append(prob_vec)

        except Exception as e:
            msg = f'  [ERROR] PESTO batch [{batch_start}:{batch_end}]: {e}'
            traceback.print_exc()
            if batch_start == 0:
                print(msg)
                pbar.close()
                return None, None, None, None
            print(msg)
            for _ in range(batch_end - batch_start):
                all_pred_labels.append(None)
                all_pred_probs.append(None)
                all_f0_hz.append(None)
                # v3: NaN for failed trials in .npz (keep alignment with JSON)
                all_confidence.append(np.nan)
                all_activations.append(None)
            errors.extend(range(batch_start, batch_end))

        pbar.update(batch_end - batch_start)

    pbar.close()

    # ------------------------------------------------------------------
    # 5. Build output dict
    # ------------------------------------------------------------------
    if template:
        result = dict(template)
    else:
        result = {}

    # Remove bez2018 peripheral-model config keys
    for key in BEZ2018_KEYS:
        result.pop(key, None)

    # Update prediction arrays — integer labels + probability vectors
    result['f0_label:labels_pred'] = all_pred_labels
    result['f0_label:probs_out'] = all_pred_probs

    # Update metadata
    result['experiment_name'] = experiment_name
    result['model_name'] = 'PESTO'
    result['timestamp'] = datetime.now().isoformat()

    # Add PESTO-specific config
    result['pesto_config'] = {
        'model': 'PESTO',
        'parameters': '130k',
        'step_size_ms': step_size,
        'reduction': 'alwa',
        'aggregation': 'median',
        'checkpoint': 'mir-1k_g7',
        'n_classes': N_CLASSES,
    }

    if errors:
        print(f'  ⚠️  {len(errors)} stimuli had errors and were set to None')

    n_valid = sum(1 for v in all_pred_labels if v is not None)
    print(f'  ✅ Done — {n_valid}/{n_stimuli} valid predictions')
    return result, all_f0_hz, all_confidence, all_activations


